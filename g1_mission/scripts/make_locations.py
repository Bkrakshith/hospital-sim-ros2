#!/usr/bin/env python3
"""Regenerate config/locations.yaml and config/instruments.yaml from the sim world (g1-mujoco-sim/worlds/
theatre_setup.json + hospital-sim-env/isaac/scene/layout.py). Run after g1-mujoco-sim/build_world.py whenever the theatre set moves.

    python ros2_ws/src/hospital-sim-ros2/g1_mission/scripts/make_locations.py
Map frame = sim world frame (true for the hospital_gt map; for a SLAM map, transform first).
"""
import importlib.util
import json
import math
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
# master repo root: $HG1_ROOT (env.sh), else from this file (ros2_ws/src/hospital-sim-ros2/g1_mission/scripts/)
REPO = os.environ.get("HG1_ROOT") or os.path.abspath(os.path.join(PKG, "..", "..", "..", ".."))


def main():
    setup = json.load(open(os.path.join(REPO, "g1-mujoco-sim", "worlds", "theatre_setup.json")))
    spec = importlib.util.spec_from_file_location("layout", os.path.join(REPO, "hospital-sim-env", "isaac", "scene", "layout.py"))
    L = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(L)
    ox, oy, _ = L.WING_ORIGIN
    st = setup["station"]

    def wing(x, y, yaw_deg, note):
        return {"x": round(x + ox, 3), "y": round(y + oy, 3), "yaw": round(math.radians(yaw_deg), 4), "note": note}

    def local(fwd, left, dyaw, note):
        c, s = math.cos(st["yaw"]), math.sin(st["yaw"])
        return {"x": round(st["x"] + fwd * c - left * s, 3), "y": round(st["y"] + fwd * s + left * c, 3),
                "yaw": round(st["yaw"] + dyaw, 4), "note": note}

    hs = setup.get("handover_station", st)
    separate = abs(hs["x"] - st["x"]) + abs(hs["y"] - st["y"]) > 0.05
    locs = {
        "theatre_instrument_table": dict(round_st(st), fine_align=True,
                                         note="pelvis pose lined up at the instrument table (FineAlign target)"),
        "theatre_surgeon_side": (dict(round_st(hs), fine_align=True,
                                      note="handover stance: surgeon's hand within reach (hospital-sim-env/objects/placements.yaml)")
                                 if separate else
                                 local(0.0, -0.45, -math.pi / 2, "beside the station, facing the surgeon stand-in")),
        "theatre_door": wing(8.0, -11.2, -90, "just inside the theatre door, facing south"),
        "corridor_theatre": wing(8.0, -8.0, -90, "surgical corridor in front of the theatre door"),
        "corridor_west": wing(-9.0, -8.0, 0, "surgical corridor, west end (default spawn)"),
        "sterile_store": wing(-8.0, -12.0, -90, "inside the sterile store door"),
        "scrub_room": wing(-2.0, -12.0, -90, "inside the scrub room door"),
        # main hospital + rest of the wing (added 2026-10-09 with the hospital_full SLAM map; world frame)
        "main_lobby": {"x": 0.0, "y": 0.0, "yaw": 0.0, "note": "main lobby in front of the reception desk (survey start)"},
        "se_lobby": {"x": 19.0, "y": -1.5, "yaw": -1.5708, "note": "hospital SE lobby, north of the door to the wing"},
        "pre_op": wing(-6.0, -4.35, 180, "pre-op bay, west of its door"),
        "pacu": wing(6.0, -4.05, 0, "recovery (PACU), east of its door"),
        "east_wing_corridor": {"x": 18.8, "y": 20.0, "yaw": 1.5708, "note": "main hospital east-wing corridor"},
        "west_wing_corridor": {"x": -40.0, "y": 20.0, "yaw": 1.5708, "note": "main hospital west-wing corridor"},
    }
    with open(os.path.join(PKG, "config", "locations.yaml"), "w") as f:
        f.write("# Named locations, map frame (= sim world frame: maps/hospital_full and maps/hospital_gt). GENERATED by "
                "scripts/make_locations.py\n# from g1-mujoco-sim/worlds/theatre_setup.json + hospital-sim-env/isaac/scene/layout.py; "
                "yaw in rad. fine_align: FineAlign after Nav2.\n"
                f"# theatre set source: {setup.get('source', 'standin')}. handover_station: where the Handover "
                "skill runs (mission.yaml handover_station: auto).\n")
        yaml.safe_dump({"handover_station": "theatre_surgeon_side" if separate else "theatre_instrument_table",
                        "theatre_source": setup.get("source", "standin"), "locations": locs}, f, sort_keys=False)
    inst = {}
    for name, e in setup["instruments"].items():
        inst[name] = {"desc": e["desc"], "length": round(e["length"], 4), "grasp_z": e["grasp_z"],
                      "handle_z": e["handle_z"], "approach_axis": e.get("approach_axis", "y"),
                      "mass": e["mass"], "rack_slot": e["slot"], "standin": e["standin"],
                      "perception_label": name}
    with open(os.path.join(PKG, "config", "instruments.yaml"), "w") as f:
        f.write("# Instrument catalogue (object frame: tip at the origin, +z towards the handle; grasp_z / handle_z "
                "along +z, m).\n# GENERATED by scripts/make_locations.py from g1-mujoco-sim/worlds/theatre_setup.json "
                "(hospital-sim-env/objects/catalog.json).\n# standin: procedural model (hospital-sim-env/objects has no scanned/CAD mesh for it). "
                "perception_label = label in /g1/perception/detections.\n# Per-instrument grasp tuning: "
                "grasp_overrides.yaml (merged at load by g1_mission.config.load_catalog).\n")
        yaml.safe_dump({"instruments": inst}, f, sort_keys=False)
    print(f"{len(locs)} locations, {len(inst)} instruments written to {os.path.join(PKG, 'config')}")


def round_st(st):
    return {"x": round(st["x"], 3), "y": round(st["y"], 3), "yaw": round(st["yaw"], 4)}


if __name__ == "__main__":
    main()
